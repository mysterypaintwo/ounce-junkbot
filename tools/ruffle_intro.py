#!/usr/bin/env python3
"""Render the original intro SWF with Ruffle into a flipbook atlas.

Ruffle is a Flash Player emulator (the same renderer Newgrounds uses), so it
reproduces the SWF timeline, gradients, colour transforms and text instead of
guessing the display list like the old swfrender-based timeline simulator.
Frames are rasterised at the SWF's native 200x200 with no resampling. The game
upscales them 2x with nearest-neighbour, keeping every source pixel exact.

Usage:
    python3 tools/ruffle_intro.py <intro.swf> <out-dir> [exporter-path]

The exporter can be supplied with RUFFLE_EXPORTER. The release generator builds
and caches it automatically (or downloads it with --ruffle-exporter-url); when
using this tool directly, place ruffle-exporter on PATH or set RUFFLE_EXPORTER.
"""

from __future__ import annotations

import hashlib
import os
import shutil
import struct
import subprocess
import sys
import tempfile
from io import BytesIO
from pathlib import Path

from PIL import Image

SCALE = 1
FRAME_W = 200
FRAME_H = 200
COLS = 16
PAD = 2


def find_exporter(explicit: str | None) -> str | None:
    if explicit:
        return explicit
    env = os.environ.get("RUFFLE_EXPORTER")
    if env and Path(env).exists():
        return env
    found = shutil.which("ruffle-exporter")
    if found:
        return found
    return None


def pack_atlas(images: list[Image.Image], sequence: list[int], out: Path) -> None:
    stride = FRAME_W + PAD * 2
    rows = (len(images) + COLS - 1) // COLS
    atlas = Image.new("RGBA", (COLS * stride, rows * stride), (0, 0, 0, 0))
    lines: list[str] = []
    for i, image in enumerate(images):
        cell_x = (i % COLS) * stride
        cell_y = (i // COLS) * stride
        x, y = cell_x + PAD, cell_y + PAD
        # Replicate edge pixels into the gutter so nearest-neighbour sampling
        # can never pull in a neighbouring frame at the cel boundary.
        expanded = Image.new("RGBA", (stride, stride), (0, 0, 0, 0))
        expanded.paste(image, (PAD, PAD))
        expanded.paste(image.crop((0, 0, 1, FRAME_H)).resize((PAD, FRAME_H), Image.Resampling.NEAREST),
                        (0, PAD))
        expanded.paste(image.crop((FRAME_W - 1, 0, FRAME_W, FRAME_H)).resize((PAD, FRAME_H), Image.Resampling.NEAREST),
                        (FRAME_W + PAD, PAD))
        expanded.paste(image.crop((0, 0, FRAME_W, 1)).resize((FRAME_W, PAD), Image.Resampling.NEAREST),
                        (PAD, 0))
        expanded.paste(image.crop((0, FRAME_H - 1, FRAME_W, FRAME_H)).resize((FRAME_W, PAD), Image.Resampling.NEAREST),
                        (PAD, FRAME_H + PAD))
        for sx, sy, dx, dy in ((0, 0, 0, 0),
                               (FRAME_W - 1, 0, FRAME_W + PAD, 0),
                               (0, FRAME_H - 1, 0, FRAME_H + PAD),
                               (FRAME_W - 1, FRAME_H - 1, FRAME_W + PAD, FRAME_H + PAD)):
            expanded.paste(image.getpixel((sx, sy)),
                           (dx, dy, dx + PAD, dy + PAD))
        atlas.paste(expanded, (cell_x, cell_y))
        lines.append(f"intro_{i:04d}\t{x}\t{y}\t{FRAME_W}\t{FRAME_H}\n")
    out.mkdir(parents=True, exist_ok=True)
    atlas.save(out / "atlas.png")
    (out / "atlas.tsv").write_text("".join(lines))
    (out / "seq.bin").write_bytes(b"".join(struct.pack("<H", i) for i in sequence))
    (out / "ruffle.txt").write_text(f"generated by Ruffle exporter at {SCALE}x, box-filtered to {FRAME_W}x{FRAME_H}\n")


def main() -> int:
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    swf = Path(sys.argv[1]).resolve()
    out = Path(sys.argv[2]).resolve()
    exporter = find_exporter(sys.argv[3] if len(sys.argv) > 3 else None)
    if not exporter:
        print("ruffle_intro: Ruffle exporter not found (set RUFFLE_EXPORTER)")
        return 3

    with tempfile.TemporaryDirectory(prefix="jb_ruffle_") as tmp:
        frames_dir = Path(tmp) / "frames"
        result = subprocess.run(
            [exporter, str(swf), str(frames_dir), "--frames", "all",
             "--scale", str(SCALE), "--silent"],
            capture_output=True, text=True)
        if result.returncode != 0:
            print(f"ruffle_intro: exporter failed: {result.stderr[-300:]}")
            return 4
        files = sorted(frames_dir.glob("*.png"))
        if len(files) != 480:
            print(f"ruffle_intro: expected 480 frames, got {len(files)}")
            return 5

        unique: list[Image.Image] = []
        lookup: dict[bytes, int] = {}
        sequence: list[int] = []
        for path in files:
            with Image.open(path) as src:
                if src.size != (FRAME_W, FRAME_H):
                    raise RuntimeError(
                        f"{path.name}: expected {FRAME_W}x{FRAME_H} native frame, got {src.size}")
                image = src.convert("RGB")
            digest = hashlib.sha256(image.tobytes()).digest()
            index = lookup.get(digest)
            if index is None:
                index = len(unique)
                lookup[digest] = index
                unique.append(image)
            sequence.append(index)

    pack_atlas(unique, sequence, out)
    print(f"intro: {len(unique)} unique flipbook frames, {len(sequence)} steps (Ruffle {SCALE}x)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
