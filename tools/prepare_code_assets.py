def clean_key(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", value.lower()).strip("_")


def full_key(value: str) -> str:
    stem = value
    for ext in (".png", ".bmp", ".wav", ".mp3"):
        if stem.lower().endswith(ext):
            stem = stem[:-len(ext)]
            break
    return clean_key(stem)


def audio_key(value: str) -> str:
    stem = value
    for ext in (".wav", ".mp3"):
        if stem.lower().endswith(ext):
            stem = stem[:-len(ext)]
            break
    return clean_key(stem)


def cstr(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_palettes() -> None:
    palettes = [
        ("main", list(reversed(JUNKBOT_MAIN))),
        ("ui", list(reversed(JUNKBOT_UI))),
        ("lose", list(reversed(JUNKBOT_LOSE))),
        ("grayscale", GRAYSCALE),
        ("system_win", SYSTEM_WIN),
        ("system_mac", SYSTEM_MAC),
    ]
    lines = [
        "/* Generated by tools/prepare_code_assets.py -- do not edit. */",
        "#ifndef JUNKBOT_PALETTES_H", "#define JUNKBOT_PALETTES_H", "",
    ]
    for name, palette in palettes:
        if len(palette) != 256:
            raise SystemExit(f"palette {name} is not 256 entries")
        lines += [f"static const unsigned char jb_palette_{name}[256][3] = {{"]
        for r, g, b in palette:
            lines.append(f"    {{ {r}, {g}, {b} }},")
        lines += ["};", ""]
    lines += ["#endif", ""]
    (INCLUDE / "jb_palettes.h").write_text("\n".join(lines), encoding="utf-8")
    print("include/jb_palettes.h: 6 palettes")


def write_asset_names() -> None:
    lines = [
        "/* Generated by tools/prepare_code_assets.py -- do not edit. */",
        "#ifndef JUNKBOT_ASSET_NAMES_H", "#define JUNKBOT_ASSET_NAMES_H", "",
        "typedef struct { const char *output; const char *key; } JbAudioName;",
        "typedef struct { const char *output; const char *source; } JbMenuArt;",
        "",
    ]
    for label, values in (("SFX", SFX_FILES), ("MUSIC", MUSIC_FILES)):
        lines.append(f"static const JbAudioName jb_{label.lower()}_names[] = {{")
        for value in values:
            lines.append(f'    {{ {cstr(value)}, {cstr(audio_key(value))} }},')
        lines += ["};", f"#define JB_{label}_NAME_COUNT {len(values)}", ""]
    lines.append("static const JbMenuArt jb_menu_art[] = {")
    for output, source in MENU_ART:
        lines.append(f"    {{ {cstr(output)}, {cstr(full_key(source))} }},")
    lines += ["};", f"#define JB_MENU_ART_COUNT {len(MENU_ART)}", "", "#endif", ""]
    (INCLUDE / "jb_asset_names.h").write_text("\n".join(lines), encoding="utf-8")
    print(f"include/jb_asset_names.h: {len(SFX_FILES)} SFX, "
          f"{len(MUSIC_FILES)} music, {len(MENU_ART)} menu")


def write_points() -> None:
    raw = json.loads((DATA / "bitmap_points.json").read_text())
    entries = []
    for name, value in raw.items():
        key = full_key(name)
        entries.append((key, int(value.get("regX", 0)), int(value.get("regY", 0)),
                        int(value.get("scrollX", 0)), int(value.get("scrollY", 0))))
    entries.sort(key=lambda row: row[0])
    out = bytearray(b"JBP1")
    out += struct.pack("<I", len(entries))
    for key, rx, ry, sx, sy in entries:
        encoded = key.encode("utf-8")
        out += struct.pack("<Ihhhh", len(encoded), rx, ry, sx, sy)
        out += encoded
    (ROMFS / "manifests/points.bin").write_bytes(out)
    print(f"romfs/manifests/points.bin: {len(entries)} registration points")


def write_recipes() -> None:
    """Split composition recipes into one manifest per rendered atlas.

    The host pipeline composes sprites and backgrounds separately; the
    on-console Director prep path needs the same split so it can write the
    engine's four virtual atlases without a Python dependency.
    """
    groups = json.loads((DATA / "sprite_recipes.json").read_text())
    outputs = {
        "sprites.json": "sprites.bin",
        "backgrounds.json": "backgrounds.bin",
        "Undercover Exclusive/sprites.json": "undercover_sprites.bin",
        "Undercover Exclusive/backgrounds.json": "undercover_backgrounds.bin",
    }
    for group, output in outputs.items():
        spec_map = groups.get(group, {})
        frames = []
        for frame_name, spec in spec_map.items():
            if isinstance(spec, list):
                layers, crop = spec, None
            else:
                layers = spec.get("layers", [])
                crop = spec.get("outputCrop")
            encoded_layers = []
            for item in layers:
                if isinstance(item, str):
                    item = {"source": item}
                source = full_key(str(item["source"]))
                points = full_key(str(item.get("pointsFrom") or item["source"]))
                ox, oy = (int(value) for value in item.get("offset", [0, 0]))
                transparent = item.get("transparent") or []
                key = tuple(int(v) for v in transparent[0][:3]) if transparent else (255, 255, 255)
                flags = 1 if item.get("keyWhite") else 0
                encoded_layers.append((source, points, ox, oy, flags, key))
            if not encoded_layers:
                continue
            crop_values = tuple(int(v) for v in crop) if crop else (0, 0, 0, 0)
            frames.append((frame_name, encoded_layers, crop_values))
        frames.sort(key=lambda row: row[0])

        out = bytearray(b"JBR1")
        out += struct.pack("<I", len(frames))
        for frame_name, layers, crop in frames:
            name = frame_name.encode("utf-8")
            out += struct.pack("<II", len(name), len(layers))
            out += name
            for source, points, ox, oy, flags, key in layers:
                src = source.encode("utf-8")
                pts = points.encode("utf-8")
                out += struct.pack("<IIiiIB3B", len(src), len(pts), ox, oy,
                                   flags, 0, key[0], key[1], key[2])
                out += src + pts
            out += struct.pack("<IIII", *crop)
        path = ROMFS / "manifests" / output
        path.write_bytes(out)
        layer_count = sum(len(row[1]) for row in frames)
        print(f"romfs/manifests/{output}: {len(frames)} frames, {layer_count} layers")


def write_silent_wav(path: Path) -> None:
    samples = b"\0\0" * 1600
    with wave.open(str(path), "wb") as fp:
        fp.setnchannels(1)
        fp.setsampwidth(2)
        fp.setframerate(16000)
        fp.writeframes(samples)


def write_plaques() -> None:
    try:
        from PIL import Image, ImageDraw, ImageFont
    except ImportError:
        print("PIL unavailable; skipping procedural plaques")
        return
    font_path = ROMFS / "fonts/04B_08__.TTF"
    font = ImageFont.truetype(str(font_path), 10)
    menus = ROMFS / "menus"
    menus.mkdir(parents=True, exist_ok=True)
    specs = [
        ("download_in_progress.png", 124, 25,
         [("DOWNLOAD", 0, 0), ("IN", 106, 0), ("PROGRESS", 15, 15)]),
        ("ready_to_play.png", 92, 25,
         [("READY", 0, 0), ("TO", 70, 0), ("PLAY", 23, 15)]),
    ]
    for name, width, height, words in specs:
        image = Image.new("RGBA", (width, height), (0, 0, 0, 0))
        draw = ImageDraw.Draw(image)
        for text, x, y in words:
            draw.text((x, y), text, font=font, fill=(255, 255, 255, 255))
        image.save(menus / name)
    transparent = Image.new("RGBA", (1, 1), (0, 0, 0, 0))
    for name in ("sprites.png", "backgrounds.png"):
        directory = ROMFS / "sprites/undercover"
        directory.mkdir(parents=True, exist_ok=True)
        transparent.save(directory / name)
        (directory / name.replace(".png", ".tsv")).write_text("", encoding="utf-8")
    print("romfs/menus: procedural plaques and empty Undercover atlases")


def write_offsets() -> None:
    data = json.loads((DATA / "junkbot_offsets.json").read_text())
    lines = [
        "/* Generated by tools/prepare_code_assets.py -- do not edit. */",
        "#ifndef JUNKBOT_OFFSETS_H", "#define JUNKBOT_OFFSETS_H", "",
        "typedef struct { const char *sprite; int x, y; } JbOffset;", "",
        "static const JbOffset jb_offsets[] = {",
    ]
    count = 0
    for frames in data.values():
        for frame in frames:
            if "sprite" not in frame or "offset" not in frame:
                continue
            offset = frame["offset"]
            lines.append(f'    {{ "{frame["sprite"]}", {offset["x"]}, {offset["y"]} }},')
            count += 1
    lines += ["};", "", "#endif", ""]
    (INCLUDE / "jb_offsets.h").write_text("\n".join(lines), encoding="utf-8")
    print(f"include/jb_offsets.h: {count} offsets")


def main() -> None:
    if ROMFS.exists():
        shutil.rmtree(ROMFS)
    (ROMFS / "fonts").mkdir(parents=True)
    (ROMFS / "manifests").mkdir(parents=True)
    (ROMFS / "levels").mkdir(parents=True)
    (ROMFS / "audio/sound-effects/undercover").mkdir(parents=True)
    shutil.copy2(HERE / "assets/04B_08__.TTF", ROMFS / "fonts/04B_08__.TTF")
    shutil.copy2(DATA / "level_listing.txt", ROMFS / "manifests/level_listing.txt")
    shutil.copy2(DATA / "Title Screen.txt", ROMFS / "levels/Title Screen.txt")
    for name in SILENT_SFX:
        write_silent_wav(ROMFS / f"audio/sound-effects/{name}.wav")
    write_palettes()
    write_asset_names()
    write_offsets()
    write_points()
    write_recipes()
    write_plaques()
    print("code-only romfs ready (no copyrighted game assets)")


if __name__ == "__main__":
    main()
