#!/usr/bin/env python3
"""Generate the small, non-copyrighted payload embedded in the NRO.

Everything in romfs/ after this script runs is either original project code
data (manifests, palettes, procedural plaques, silent placeholders) or a font.
All game-derived pixels/audio/levels live in the external junkbot.otr package.
"""

